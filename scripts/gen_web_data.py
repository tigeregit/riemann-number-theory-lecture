#!/usr/bin/env python3
"""Regenerate web/data.js from tex/data/*.dat and lean/Riemann/*.lean.

Run from the repo root:  python3 scripts/gen_web_data.py
Produces compact JSON with downsampled plot arrays, the first zeta zeros,
and the verbatim Lean sources shown in the browser tabs.
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def sample_pi():
    out, prev = [], -1
    for line in open(os.path.join(ROOT, "tex", "data", "pi_li.dat")):
        if line.startswith("#"):
            continue
        x, pi, li, xl = line.split()
        x = int(x)
        if x >= 1000 and x - prev < 200 and x < 100000:
            continue
        if x < 1000 and x - prev < 25:
            continue
        out.append([x, int(pi), round(float(li), 2), round(float(xl), 2)])
        prev = x
    return out


def sample_zeta():
    out, prev = [], -99
    for line in open(os.path.join(ROOT, "tex", "data", "zeta_real.dat")):
        if line.startswith("#"):
            continue
        s, z = map(float, line.split())
        if s - prev < 0.035:
            continue
        out.append([round(s, 3), round(z, 5)])
        prev = s
    return out


ZEROS = [14.134725, 21.022040, 25.010858, 30.424876, 32.935062, 37.586178,
         40.918719, 43.327073, 48.005150, 49.773832, 52.970321, 56.446248,
         59.347044, 60.831778]

LEAN_FILES = {"basic": "Basic", "euclid": "Euclid", "eulerproduct": "EulerProduct",
              "moebius": "Moebius", "pc": "PrimeCounting",
              "zeta": "ZetaStatements", "ex": "Exercises"}


def main():
    lean = {k: open(os.path.join(ROOT, "lean", "Riemann", v + ".lean"), encoding="utf-8").read()
            for k, v in LEAN_FILES.items()}
    obj = {"pi": sample_pi(), "zeta": sample_zeta(), "zeros": ZEROS, "lean": lean}
    dest = os.path.join(ROOT, "web", "data.js")
    with open(dest, "w", encoding="utf-8") as f:
        f.write("/* Generated by scripts/gen_web_data.py. */\n")
        f.write("window.RIEMANN_DATA = " +
                json.dumps(obj, ensure_ascii=False, separators=(",", ":")) + ";\n")
    print("wrote", dest, os.path.getsize(dest), "bytes;",
          len(obj["pi"]), "pi points,", len(obj["zeta"]), "zeta points,",
          len(lean), "Lean files")


if __name__ == "__main__":
    main()
